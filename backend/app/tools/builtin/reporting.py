"""Assemble an inspection report from what actually happened this turn.

The temptation with a "report generator" is to have it reformat whatever the
model wrote, which adds nothing - the model can already produce headings.
What it cannot do is attest to its own provenance: which documents were
really read, which tools really ran, which model really answered, under
whose clearance. Those are facts this layer holds and the model does not.

So the model supplies the findings and this supplies the evidence trail,
stamped from the turn's real state. A report that lists a source is listing
one that was genuinely retrieved, because the list comes from the executor,
not from the model's memory of its own reasoning.

The document is deliberately marked as generated by a demonstration system
carrying synthetic data: an industrial inspection report is exactly the kind
of artefact that gets forwarded out of context and mistaken for an approved
one.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any

from app.models import get_gateway
from app.tools.base import Tool, ToolArgumentError, ToolContext, ToolResult


class ReportGeneratorTool(Tool):
    id = "report-gen"
    name = "generate_report"
    description = (
        "Compile a structured inspection or diagnostic report from this "
        "conversation. Supply the title, a summary and the findings; the "
        "system attaches the evidence trail - which documents were consulted, "
        "which tools ran, which model answered and under whose clearance. "
        "Call this only when the user asks for a report."
    )

    @property
    def parameters(self) -> dict[str, Any]:
        return {
            "type": "object",
            "properties": {
                "title": {
                    "type": "string",
                    "description": "Report title, e.g. 'Pump P-204 Vibration Assessment'.",
                },
                "summary": {
                    "type": "string",
                    "description": "One paragraph stating the conclusion.",
                },
                "findings": {
                    "type": "array",
                    "items": {"type": "string"},
                    "description": (
                        "The individual findings, one per entry. Cite the "
                        "passage each came from where you have one."
                    ),
                },
                "recommendations": {
                    "type": "array",
                    "items": {"type": "string"},
                    "description": "Recommended actions, one per entry. Optional.",
                },
            },
            "required": ["title", "summary", "findings"],
        }

    def run(self, context: ToolContext, **kwargs: Any) -> ToolResult:
        title = (kwargs.get("title") or "").strip()
        summary = (kwargs.get("summary") or "").strip()
        findings = [f.strip() for f in (kwargs.get("findings") or []) if str(f).strip()]
        recommendations = [
            r.strip() for r in (kwargs.get("recommendations") or []) if str(r).strip()
        ]

        if not title or not summary or not findings:
            raise ToolArgumentError(
                "A report needs a title, a summary and at least one finding."
            )

        gateway = get_gateway()

        # The evidence trail is taken from the turn, not from the arguments -
        # the model cannot add a source that was never retrieved.
        sources = []
        seen: set[str] = set()
        for citation in context.turn_citations:
            document_id = citation.get("documentId")
            if document_id in seen:
                continue
            seen.add(document_id)
            sources.append(
                {
                    "documentId": document_id,
                    "title": citation.get("title", ""),
                    "location": citation.get("page", ""),
                }
            )

        report = {
            "title": title,
            "summary": summary,
            "findings": findings,
            "recommendations": recommendations,
            "question": context.question,
            "generatedAt": datetime.now().isoformat(timespec="seconds"),
            "preparedFor": context.user.name,
            "clearance": context.user.scope_label,
            "agent": context.agent.name if context.agent else "No agent",
            "model": gateway.model if gateway.is_configured else "No model configured",
            "onPremise": gateway.is_on_premise,
            "sources": sources,
            "toolsUsed": sorted(set(context.tools_used)),
            "disclaimer": (
                "Generated by a demonstration system operating on synthetic, "
                "fictional data. Not an approved plant document. The site's "
                "controlled procedure and a qualified engineer take precedence."
            ),
        }

        evidence = (
            f"{len(sources)} source document(s)" if sources else "no source documents"
        )
        return ToolResult(
            content=(
                f"Report '{title}' compiled with {len(findings)} finding(s) and "
                f"{evidence}. It has been attached to your reply - tell the "
                "user it is ready and summarise it briefly. Do not re-type the "
                "whole report."
            ),
            data={"report": report},
        )


__all__ = ["ReportGeneratorTool"]
